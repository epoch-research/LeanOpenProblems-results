def compute_states(n, save_points):
    k, c1, c2, acc = 0, 1, 1, 0
    states = {}
    if 0 in save_points:
        states[0] = (k, c1, c2, acc)
    for i in range(1, n + 1):
        # We compute the term first
        term = c1**2 * c2**2
        acc += term
        # Then we step
        k_next = k + 1
        c1_next = c1 * (n - k) // (k + 1)
        c2_next = c2 * (n + k) // (k + 1)
        k, c1, c2 = k_next, c1_next, c2_next
        if i in save_points:
            states[i] = (k, c1, c2, acc)
    return states

