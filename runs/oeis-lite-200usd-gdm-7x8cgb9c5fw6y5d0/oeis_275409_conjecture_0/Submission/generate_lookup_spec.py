import math

# Precompute a_fast in python
a_vals = []
for n in range(200):
    count = 0
    lim_w = int(math.isqrt(n // 2))
    for w in range(lim_w + 1):
        rem1 = n - 2 * w**2
        lim_x = int(math.isqrt(rem1))
        for x in range(lim_x + 1):
            rem2 = rem1 - x**2
            lim_y = int(math.isqrt(rem2))
            for y in range(lim_y + 1):
                z2 = rem2 - y**2
                z = int(math.isqrt(z2))
                if z * z == z2:
                    val = w + x + 2*y + 4*z
                    # is_square
                    s = int(math.isqrt(val))
                    if s * s == val:
                        count += 1
    a_vals.append(count)

